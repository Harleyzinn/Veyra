export function resolvedTheme(prefs: Record<string, string>, dark: boolean) {
  if (prefs.theme === "system")
    return themes.find(
      (t) => t.id === (dark ? "classic-dark" : "classic-light"),
    )!;
  return (
    themes.find((t) => t.id === prefs.theme) ||
    themes.find((t) => t.id === "emerald")!
  );
}
export function readableAccent(theme: Theme, requested: string) {
  if (!/^#[0-9a-f]{6}$/i.test(requested)) return theme.accent;
  const luminance = (hex: string) => {
    const c = hex
      .slice(1)
      .match(/../g)!
      .map((v) => parseInt(v, 16) / 255)
      .map((n) => (n <= 0.04045 ? n / 12.92 : ((n + 0.055) / 1.055) ** 2.4));
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
  };
  const a = luminance(requested),
    b = luminance(theme.onAccent),
    ratio = (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05);
  return ratio >= 4.5 ? requested : theme.accent;
}
